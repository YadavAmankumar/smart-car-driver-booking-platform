export function getServiceAreaFromPincode(
  pincode: string,
): ServiceArea | null {
  for (const [area, pincodes] of Object.entries(LOCAL_PINCODES)) {
    if (pincodes.includes(pincode)) {
      return area as ServiceArea;
    }
  }

  return null;
}

export function extractPincode(locationLabel: string): string | null {
  const match = locationLabel.match(/\b[1-9][0-9]{5}\b/);
  return match?.[0] ?? null;
}

export function isLocalPincode(pincode: string): boolean {
  return getServiceAreaFromPincode(pincode) !== null;
}
